#!/bin/zsh
# Regenerates procon_pdf.h, the Pro Controller drawing the Settings window shows, from assets/Controller_ProCon.svg
# (Ryujinx, MIT): AppKit draws the SVG into a vector PDF, embedded as bytes so the library needs no resource bundle and
# Core Graphics draws it the same on Mac and iOS.
set -eu
here=${0:A:h}; lib=${here:h}; T=$(mktemp -d); trap 'rm -rf $T' EXIT
xcrun clang -fobjc-arc $here/svg_to_pdf.m -framework AppKit -o $T/render
$T/render $lib/assets/Controller_ProCon.svg $T/preview.png $T/procon.pdf
{ echo "/* Generated by tools/make_procon_pdf.sh from assets/Controller_ProCon.svg (Ryujinx, MIT license). */"
  echo "static const unsigned char procon_pdf[] = {"; xxd -i < $T/procon.pdf; echo "};"; } > $lib/procon_pdf.h
echo "procon_pdf.h: $(stat -f %z $T/procon.pdf) bytes of PDF"
